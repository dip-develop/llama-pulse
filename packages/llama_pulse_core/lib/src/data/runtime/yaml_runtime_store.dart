import 'dart:io';

import 'package:built_value/serializer.dart';
import 'package:path/path.dart' as p;

import '../../domain/entities/runtime_index.dart';
import '../../domain/entities/runtime_install_ref.dart';
import '../../domain/entities/runtime_manifest.dart';
import '../../domain/gateways/runtime_store.dart';
import '../../domain/runtime/runtime_backend.dart';
import '../config/app_paths.dart';
import '../config/yaml_decoder.dart';
import '../config/yaml_encoder.dart';
import '../serialization/serializers.dart' as core;

/// A [RuntimeStore] backed by YAML files under `<config>/runtime/`.
///
/// `index.yaml` is rewritten atomically. A malformed or stale index reads as
/// empty and is regenerated by the next mutation, so a corrupt index never
/// blocks an install or a removal.
final class YamlRuntimeStore implements RuntimeStore {
  /// Creates a store rooted at [paths]'s configuration directory.
  ///
  /// [serializers] defaults to the core serializers; tests and future callers
  /// may pass their own registry. [clock] is injectable so orphan cleanup can
  /// be tested without waiting.
  factory YamlRuntimeStore({
    required AppPaths paths,
    Serializers? serializers,
    DateTime Function()? clock,
  }) => YamlRuntimeStore._(
    paths,
    serializers ?? core.serializers,
    clock ?? DateTime.now,
  );

  YamlRuntimeStore._(this._paths, this._serializers, this._clock);

  final AppPaths _paths;
  final Serializers _serializers;
  final DateTime Function() _clock;

  static const String _indexName = 'index.yaml';
  static const String _manifestName = 'runtime.yaml';
  static const String _stagingPrefix = '.tmp-';

  static int _tempCounter = 0;

  static final RegExp _tagPattern = RegExp(r'^[A-Za-z0-9][A-Za-z0-9._-]*$');

  String get _runtimeRoot => _paths.runtimeDirectory;

  String get _indexFile => p.join(_runtimeRoot, _indexName);

  @override
  String installDirectory(String tag, RuntimeBackend backend) {
    _validateTag(tag);
    return p.join(_runtimeRoot, tag, backend.id);
  }

  @override
  Future<List<RuntimeInstallRef>> list() async {
    try {
      final current = await index();
      return current.installed.toList(growable: false);
    } on Object {
      return const <RuntimeInstallRef>[];
    }
  }

  @override
  Future<RuntimeIndex> index() async {
    final file = File(_indexFile);
    try {
      if (!await file.exists()) {
        return RuntimeIndex.empty();
      }
      final document = YamlDecoder.decode(await file.readAsString());
      if (document['schemaVersion'] != RuntimeIndex.schemaVersion) {
        return RuntimeIndex.empty();
      }
      final body = Map<String, Object?>.from(document)..remove('schemaVersion');
      final parsed = _serializers.deserializeWith(
        RuntimeIndex.serializer,
        body,
      );
      return parsed ?? RuntimeIndex.empty();
    } on Object {
      return RuntimeIndex.empty();
    }
  }

  @override
  Future<RuntimeManifest?> manifest(String tag, RuntimeBackend backend) async {
    try {
      final file = File(p.join(installDirectory(tag, backend), _manifestName));
      if (!await file.exists()) {
        return null;
      }
      final document = YamlDecoder.decode(await file.readAsString());
      if (document['schemaVersion'] != RuntimeManifest.schemaVersion) {
        return null;
      }
      final body = Map<String, Object?>.from(document)..remove('schemaVersion');
      return _serializers.deserializeWith(RuntimeManifest.serializer, body);
    } on Object {
      return null;
    }
  }

  @override
  Future<void> select(String tag, RuntimeBackend backend) async {
    final selected = await manifest(tag, backend);
    if (selected == null) {
      throw StateError('runtime $tag/${backend.id} is not installed');
    }
    final current = await index();
    final installed = <RuntimeInstallRef>[
      for (final install in current.installed)
        if (!(install.tag == tag && install.backend == backend)) install,
      _refFor(selected),
    ];
    await _writeIndex(
      current.rebuild(
        (b) => b
          ..selectedTag = tag
          ..selectedBackend = backend
          ..installed.replace(installed),
      ),
    );
  }

  @override
  Future<void> remove(String tag, RuntimeBackend backend) async {
    final directory = Directory(installDirectory(tag, backend));
    try {
      if (await directory.exists()) {
        await directory.delete(recursive: true);
      }
    } on FileSystemException {
      // A concurrent removal already deleted the tree; the index still needs
      // the entry dropped, so continue.
    }
    final current = await index();
    final clearsSelection =
        current.selectedTag == tag && current.selectedBackend == backend;
    final installed = <RuntimeInstallRef>[
      for (final install in current.installed)
        if (!(install.tag == tag && install.backend == backend)) install,
    ];
    await _writeIndex(
      current.rebuild((b) {
        b.installed.replace(installed);
        if (clearsSelection) {
          b
            ..selectedTag = ''
            ..selectedBackend = null;
        }
      }),
    );
    await _deleteEmptyTagDirectory(tag);
  }

  @override
  Future<void> commit(
    RuntimeBackend backend,
    RuntimeManifest manifest,
    Directory stagingDir, {
    bool force = false,
  }) async {
    if (manifest.backend != backend) {
      throw StateError(
        'manifest backend ${manifest.backend.id} does not match $backend',
      );
    }
    _validateTag(manifest.tag);
    await _verifyStaging(stagingDir, manifest);

    final destination = Directory(installDirectory(manifest.tag, backend));
    final destinationType = await FileSystemEntity.type(
      destination.path,
      followLinks: false,
    );
    final exists = destinationType != FileSystemEntityType.notFound;
    if (exists && !force) {
      throw StateError(
        'runtime ${manifest.tag}/${backend.id} is already installed',
      );
    }
    await destination.parent.create(recursive: true);

    String? backup;
    if (exists) {
      backup =
          '${destination.path}.old-'
          '${_clock().microsecondsSinceEpoch}-${_tempCounter++}';
      await _movePath(destination.path, backup);
    }
    try {
      await stagingDir.rename(destination.path);
    } on Object {
      if (backup != null) {
        try {
          await _movePath(backup, destination.path);
        } on Object {
          // Restoring failed; the original rename error is more useful.
        }
      }
      rethrow;
    }
    if (backup != null) {
      try {
        await _deletePath(backup);
      } on Object {
        // A leftover backup is harmless; the new install is in place.
      }
    }

    await _writeManifest(destination, manifest);
    final current = await index();
    final installed = <RuntimeInstallRef>[
      for (final install in current.installed)
        if (!(install.tag == manifest.tag && install.backend == backend))
          install,
      _refFor(manifest),
    ];
    await _writeIndex(current.rebuild((b) => b..installed.replace(installed)));
  }

  @override
  Future<void> cleanupOrphans({
    Duration olderThan = const Duration(days: 1),
  }) async {
    final root = Directory(_runtimeRoot);
    if (!await root.exists()) {
      return;
    }
    final cutoff = _clock().subtract(olderThan);
    await for (final entity in root.list(followLinks: false)) {
      if (entity is! Directory) {
        continue;
      }
      if (!p.basename(entity.path).startsWith(_stagingPrefix)) {
        continue;
      }
      try {
        final modified = await _orphanTimestamp(entity);
        if (modified.isAfter(cutoff)) {
          continue;
        }
        await entity.delete(recursive: true);
      } on Object {
        // A staging directory that disappears while listing is already clean.
      }
    }
  }

  /// The newest modification time in [directory].
  ///
  /// Staging trees are written file by file, so the files are the better age
  /// signal; the directory's own timestamp is only used when it is empty.
  static Future<DateTime> _orphanTimestamp(Directory directory) async {
    DateTime? newest;
    await for (final entity in directory.list(followLinks: false)) {
      try {
        final modified = (await entity.stat()).modified;
        if (newest == null || modified.isAfter(newest)) {
          newest = modified;
        }
      } on Object {
        // A file removed by the writer is not evidence of a fresh staging run.
      }
    }
    return newest ?? (await directory.stat()).modified;
  }

  Future<void> _verifyStaging(
    Directory stagingDir,
    RuntimeManifest manifest,
  ) async {
    final root = p.normalize(p.absolute(stagingDir.path));
    final rootType = await FileSystemEntity.type(root, followLinks: false);
    if (rootType != FileSystemEntityType.directory) {
      throw StateError('staging path is not a directory: $root');
    }
    final names = <String>[
      manifest.platform.serverBinaryName,
      manifest.platform.libraryFileName,
      ...manifest.backendLibs,
    ];
    for (final name in names) {
      if (name.isEmpty ||
          name == '.' ||
          name == '..' ||
          p.basename(name) != name) {
        throw StateError('manifest names an unsafe runtime file: $name');
      }
      final path = p.join(root, name);
      if (!p.isWithin(root, path)) {
        throw StateError('runtime file escapes the staging directory: $name');
      }
      final type = await FileSystemEntity.type(path, followLinks: false);
      if (type == FileSystemEntityType.link) {
        throw StateError('runtime file is a symlink: $name');
      }
      if (type != FileSystemEntityType.file) {
        throw StateError('staged runtime is missing the regular file $name');
      }
    }
  }

  Future<void> _writeIndex(RuntimeIndex current) async {
    final serialized = _serializers.serializeWith(
      RuntimeIndex.serializer,
      current,
    );
    if (serialized is! Map<String, Object?>) {
      throw StateError('RuntimeIndex did not serialize to a map');
    }
    await _writeDocument(File(_indexFile), <String, Object?>{
      'schemaVersion': RuntimeIndex.schemaVersion,
      ...serialized,
    });
  }

  Future<void> _writeManifest(
    Directory installDirectory,
    RuntimeManifest manifest,
  ) async {
    final serialized = _serializers.serializeWith(
      RuntimeManifest.serializer,
      manifest,
    );
    if (serialized is! Map<String, Object?>) {
      throw StateError('RuntimeManifest did not serialize to a map');
    }
    await _writeDocument(
      File(p.join(installDirectory.path, _manifestName)),
      <String, Object?>{
        'schemaVersion': RuntimeManifest.schemaVersion,
        ...serialized,
      },
    );
  }

  Future<void> _writeDocument(File file, Map<String, Object?> document) async {
    await file.parent.create(recursive: true);
    final temporary = File('${file.path}.tmp.$pid.${_tempCounter++}');
    try {
      await temporary.writeAsString(YamlEncoder.encode(document), flush: true);
      try {
        await temporary.rename(file.path);
      } on FileSystemException {
        // Windows cannot rename over an existing file.
        if (await file.exists()) {
          await file.delete();
        }
        await temporary.rename(file.path);
      }
    } on Object {
      try {
        if (await temporary.exists()) {
          await temporary.delete();
        }
      } on Object {
        // The original failure is more useful than a cleanup failure.
      }
      rethrow;
    }
  }

  Future<void> _deleteEmptyTagDirectory(String tag) async {
    final tagDirectory = Directory(p.join(_runtimeRoot, tag));
    try {
      if (await tagDirectory.exists() &&
          await tagDirectory.list(followLinks: false).isEmpty) {
        await tagDirectory.delete();
      }
    } on Object {
      // A race with another writer is harmless.
    }
  }

  static RuntimeInstallRef _refFor(RuntimeManifest manifest) =>
      RuntimeInstallRef(
        (b) => b
          ..tag = manifest.tag
          ..backend = manifest.backend
          ..platform = manifest.platform
          ..installedAtEpochMs = manifest.installedAtEpochMs
          ..sizeBytes = manifest.sizeBytes,
      );

  static Future<void> _movePath(String from, String to) async {
    final type = await FileSystemEntity.type(from, followLinks: false);
    if (type == FileSystemEntityType.directory) {
      await Directory(from).rename(to);
    } else {
      await File(from).rename(to);
    }
  }

  static Future<void> _deletePath(String path) async {
    final type = await FileSystemEntity.type(path, followLinks: false);
    if (type == FileSystemEntityType.directory) {
      await Directory(path).delete(recursive: true);
    } else if (type != FileSystemEntityType.notFound) {
      await File(path).delete();
    }
  }

  static void _validateTag(String tag) {
    if (!_tagPattern.hasMatch(tag) || tag == '.' || tag == '..') {
      throw ArgumentError.value(
        tag,
        'tag',
        'must be a simple runtime tag such as v0.8.0',
      );
    }
  }
}
